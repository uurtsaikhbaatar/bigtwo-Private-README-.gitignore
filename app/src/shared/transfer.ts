/**
 * Тоглогч хоорондын чип шилжүүлгийн дүрэм.
 *
 * Сервер ба апп ХОЁУЛАА эндээс уншина — апп шимтгэлийг урьдчилан харуулж,
 * сервер жинхэнэ тооцоог хийнэ. Нэг газар байх тул хоёр тал зөрөхгүй.
 */

/** Шилжүүлгээс хасагдах шимтгэл (5%). Хүлээн авагч үлдсэнийг нь авна. */
export const TRANSFER_FEE_RATE = 0.05;
/** Нэг илгээгч 24 цагт нийт илгээж болох дээд хэмжээ. */
export const DAILY_TRANSFER_LIMIT = 5_000_000;
/** Хамгийн бага шилжүүлэг — шимтгэл тэгээр тоймлогдохоос сэргийлнэ. */
export const MIN_TRANSFER = 100;

/** Шимтгэл. Дээш тоймлох тул 1 чипээс багагүй. */
export function transferFee(amount: number): number {
  return Math.ceil(amount * TRANSFER_FEE_RATE);
}
